#!/usr/bin/env python3
"""Compile Eden's host GLSL shaders to SPIR-V and emit C++ headers.

Eden's CMake asks glslangValidator for `--variable-name`, a shaderc feature the
NDK's glslc (v2022.3) does not have.  We run glslc to a .spv and write the header
ourselves in the same shape the C++ code expects: a global `constexpr` array of
u32 named <FILE>_SPV.

Output tree: d3-android/gpu/gen/include/video_core/host_shaders/
"""
from __future__ import annotations

import argparse
import pathlib
import struct
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
EDEN = ROOT / 'reference' / 'eden'
SHADER_SRC = EDEN / 'src' / 'video_core' / 'host_shaders'
FFX = EDEN / 'externals' / 'FidelityFX-FSR' / 'ffx-fsr'
OUT = ROOT / 'd3-android' / 'gpu' / 'gen' / 'include' / 'video_core' / 'host_shaders'
GLSLC = pathlib.Path(r'D:\workspace\Gdict\android_sdk\ndk\28.2.13676358\shader-tools\windows-x86_64\glslc.exe')

EXTENSIONS = {'.comp', '.vert', '.frag'}
# Include-only fragments (no #version of their own); compiled through their users.
SKIP = {'fidelityfx_fsr.frag'}


def shader_name(path: pathlib.Path) -> str:
    return path.name.replace('.', '_')


def read_spirv(path: pathlib.Path) -> list[int]:
    data = path.read_bytes()
    if len(data) % 4:
        raise ValueError(f'{path}: SPIR-V size is not a multiple of 4')
    return list(struct.unpack(f'<{len(data)//4}I', data))


def emit_header(name: str, words: list[int], dest: pathlib.Path) -> None:
    var = f'{name.upper()}_SPV'
    body = ',\n'.join('    ' + ', '.join(f'0x{w:08x}u' for w in words[i:i + 8])
                      for i in range(0, len(words), 8))
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(
        '// Generated by gpu/tools/gen_shaders.py -- do not edit.\n'
        '#pragma once\n'
        '#include <cstdint>\n\n'
        f'inline constexpr std::uint32_t {var}[] = {{\n'
        f'{body}\n'
        '};\n',
        encoding='utf-8')


def compile_one(src: pathlib.Path, tmp: pathlib.Path,
                defines: list[str] | None = None) -> list[int]:
    cmd = [str(GLSLC), '-DUseUniformBlock=1', '--target-env=vulkan1.1',
           '-I', str(FFX), '-o', str(tmp), str(src)]
    for define in defines or []:
        cmd.insert(1, f'-D{define}')
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        raise RuntimeError(f'{src.name}: {proc.stderr.strip()}')
    return read_spirv(tmp)


# Mirror of Eden's SHADER_TYPE_VARIANTS: (source, suffix, sampler, texel).
VARIANTS = [
    ('convert_msaa_to_non_msaa.frag', 'sint', 'isampler2DMS', 'ivec4'),
    ('convert_msaa_to_non_msaa.frag', 'uint', 'usampler2DMS', 'uvec4'),
    ('convert_non_msaa_to_msaa.frag', 'sint', 'isampler2D', 'ivec4'),
    ('convert_non_msaa_to_msaa.frag', 'uint', 'usampler2D', 'uvec4'),
]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--dry-run', action='store_true')
    args = parser.parse_args()

    if not GLSLC.exists():
        print(f'glslc not found: {GLSLC}', file=sys.stderr)
        return 1

    sources = sorted(p for p in SHADER_SRC.iterdir()
                     if p.suffix in EXTENSIONS and not p.name.startswith('opengl')
                     and p.name not in SKIP)
    tmp = pathlib.Path(tempfile_dir := OUT.parent / '.spv_tmp')
    tmp.mkdir(parents=True, exist_ok=True)

    ok, failed = 0, []
    jobs = [(src, shader_name(src), []) for src in sources]
    for filename, suffix, sampler, texel in VARIANTS:
        src = SHADER_SRC / filename
        stem = f'{src.stem}_{suffix}{src.suffix}'.replace('.', '_')
        jobs.append((src, stem, [f'SAMPLER_TYPE={sampler}', f'TEXEL_TYPE={texel}']))

    for src, stem, defines in jobs:
        dest = OUT / f'{stem}_spv.h'
        spv = tmp / f'{stem}.spv'
        if args.dry_run:
            print(f'would build {dest.name}')
            continue
        try:
            words = compile_one(src, spv, defines)
            emit_header(stem, words, dest)
            ok += 1
        except RuntimeError as exc:
            failed.append(str(exc))

    if not args.dry_run:
        print(f'generated {ok}/{len(jobs)} shader headers in {OUT}')
        for msg in failed:
            print(f'  FAIL {msg}', file=sys.stderr)
    return 0 if not failed else 1


if __name__ == '__main__':
    raise SystemExit(main())
